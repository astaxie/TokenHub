import { readFile } from "node:fs/promises";
import { test, expect, section, capture } from "./harness";
import { readStatementQuery, statementResponse } from "./fixtures/billing";
test.use({ sessionLanguage: "ru", locale: "ru-RU" });
test("billing rate decimal normalization preserves edits in the middle", async ({ page, api }, testInfo) => {
  api.define("POST", "/api/admin/billing/statements", input => {
    const query = readStatementQuery(input.body);
    expect(query).toMatchObject({ display_currency: "RUB", display_exchange_rate: "90.225" });
    const response = statementResponse(query, "complete");
    response.conversion = { currency: "RUB", usd_exchange_rate: "90.225" };
    response.rows[0].display_amount = "97.443";
    response.display_totals = { provider_estimate: "97.443" };
    return { json: response };
  });
  await page.goto("/billing");
  const form = section(page, "Акт сверки расходов");
  await form.getByLabel("Тип акта сверки").selectOption("provider");
  await form.getByLabel("Валюта выписки").selectOption("RUB");
  const rate = form.getByLabel("Ручной курс: единиц целевой валюты за 1 USD");
  await rate.pressSequentially("90,125");
  await expect(rate).toHaveValue("90.125");
  await rate.fill("90125");
  await rate.evaluate((input: HTMLInputElement) => input.setSelectionRange(2, 2));
  await rate.pressSequentially(",4");
  await expect(rate).toHaveValue("90.4125");
  await expect.poll(() => rate.evaluate((input: HTMLInputElement) => input.selectionStart)).toBe(4);
  await rate.fill("90.125");
  await rate.evaluate((input: HTMLInputElement) => input.setSelectionRange(2, 4));
  await rate.pressSequentially(",2");
  await expect(rate).toHaveValue("90.225");
  await form.getByRole("button", { name: "Предпросмотр акта сверки", exact: true }).click();
  const conversion = form.locator(".statement-conversion");
  await expect(conversion).toContainText("90,225");
  await capture(page, testInfo, conversion, "currency-edited-decimal", "汇率：中间插入与选区替换后保留精确数值");
  const downloaded = page.waitForEvent("download");
  await form.getByRole("button", { name: "Экспорт текущего предпросмотра в CSV", exact: true }).click();
  const csv = await readFile((await (await downloaded).path())!, "utf8");
  expect(csv).toContain('"display_exchange_rate_usd_to_currency","90.225"');
});
